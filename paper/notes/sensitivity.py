"""
Sensitivity analyses pre-specified in paper/notes/analysis_plan.md, plus one
post-hoc check (labelled as such in the plan's Deviations section). No model,
classifier or decision tree; delineator, features, qc.py and config.yaml unchanged.

    .venv/Scripts/python.exe paper/notes/sensitivity.py

  1. Complete matched sets (Design A, 1 case + 2 controls after QC): paired d per set.
  2. Design B through the same QC (pulse_ecg/qc.py via qc_exclusions._one), then the
     same primary model, secondaries and BH as group_comparison.py.
  3. POST-HOC: PTB-XL report provenance (validated_by_human, initial_autogenerated_report,
     second_opinion) for Design A cases / controls; primary model on the
     human-validated subset if it has >= 50 cases.

Outputs: out/sens1_matched_sets_designA.csv, out/qc_designB.csv, out/qc_flow_designB.csv,
         out/group_comparison_designB.csv, out/posthoc_report_provenance_designA.csv
"""

import hashlib
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "paper" / "notes"))
from pulse_ecg import io, qc  # noqa: E402
import group_comparison as gc  # noqa: E402
import qc_exclusions  # noqa: E402

PROVENANCE = ["validated_by_human", "initial_autogenerated_report", "second_opinion"]
MIN_CASES_POSTHOC = 50


def load_design_a():
    q = pd.read_csv(ROOT / "out" / "qc_designA.csv")
    kept = q[q["qc_pass"]].drop(columns="group")
    cohort = pd.read_csv(ROOT / "out" / "cohort.csv")
    a = cohort[cohort.design == "A"][["ecg_id", "group", "match_id", "age", "sex"]]
    df = kept.drop(columns="match_id").merge(a, on="ecg_id", validate="one_to_one")
    df["case"] = (df.group == "case").astype(int)
    assert len(df) == 775 and df.case.sum() == 259
    return df


# ---------------------------------------------------------------- sensitivity 1
def sens1(df):
    n_ctrl = df[df.case == 0].groupby("match_id").size()
    has_case = set(df.loc[df.case == 1, "match_id"])
    full = [m for m in has_case if n_ctrl.get(m, 0) == 2]
    assert len(full) == 159, len(full)
    sub = df[df.match_id.isin(full)]
    rows = []
    for feat, role in [(gc.PRIMARY, "primary")] + [(f, "secondary") for f in gc.SECONDARY]:
        ca = sub[sub.case == 1].set_index("match_id")[feat]
        co = sub[sub.case == 0].groupby("match_id")[feat].agg(
            lambda v: v.mean() if v.notna().all() else np.nan)
        d = (ca - co).dropna()                    # set needs case and both controls
        n = len(d)
        se = d.std(ddof=1) / np.sqrt(n)
        tc = stats.t.ppf(0.975, n - 1)
        rows.append({"feature": feat, "role": role,
                     "circularity": gc.CIRCULAR.get(feat, "not circular"),
                     "n_sets": n, "mean_d": d.mean(),
                     "d_lo": d.mean() - tc * se, "d_hi": d.mean() + tc * se,
                     "p_paired_t": stats.ttest_1samp(d, 0).pvalue,
                     "p_wilcoxon": stats.wilcoxon(d).pvalue})
    res = pd.DataFrame(rows)
    sec = res.role == "secondary"
    for p in ("p_paired_t", "p_wilcoxon"):
        res[f"q_bh_{p[2:]}"] = np.nan
        res.loc[sec, f"q_bh_{p[2:]}"] = gc.bh(res.loc[sec, p])
    res.to_csv(ROOT / "out" / "sens1_matched_sets_designA.csv", index=False)
    return res


# ---------------------------------------------------------------- sensitivity 2
def sens2():
    cohort = pd.read_csv(ROOT / "out" / "cohort.csv")
    b = cohort[cohort.design == "B"]
    with ProcessPoolExecutor() as ex:
        rows = pd.DataFrame(ex.map(qc_exclusions._one, b["ecg_id"].tolist(), chunksize=8))
    rules = qc.build_rules()
    res = qc.apply(rows, rules)                                  # blind: no group column
    res = b[["ecg_id", "group", "match_id"]].merge(res, on="ecg_id", how="left")
    assert len(res) == len(b) and res["qc_pass"].notna().all()
    res.to_csv(ROOT / "out" / "qc_designB.csv", index=False)
    flow = qc.flow(res, rules, by="group")
    flow.to_csv(ROOT / "out" / "qc_flow_designB.csv", index=False)

    kept = res[res["qc_pass"]].drop(columns="group")
    df = kept.merge(b[["ecg_id", "group", "age", "sex"]], on="ecg_id", validate="one_to_one")
    df["case"] = (df.group == "case").astype(int)
    out = pd.DataFrame([gc.row(df, gc.PRIMARY, "primary")] +
                       [gc.row(df, f, "secondary") for f in gc.SECONDARY])
    out["circularity"] = "n/a (Design B labels not P-wave-based)"
    sec = out.role == "secondary"
    out["q_bh"] = np.nan
    out.loc[sec, "q_bh"] = gc.bh(out.loc[sec, "p"])
    out.to_csv(ROOT / "out" / "group_comparison_designB.csv", index=False)
    return flow, out, df


# ---------------------------------------------------------------- post-hoc
def posthoc(df):
    db = io.ptbxl_database()[PROVENANCE]
    cohort = pd.read_csv(ROOT / "out" / "cohort.csv")
    a_all = cohort[cohort.design == "A"][["ecg_id", "group"]].join(db, on="ecg_id")
    a_qc = df[["ecg_id", "group"]].join(db, on="ecg_id")
    rows = []
    for label, d in (("cohort (pre-QC)", a_all), ("QC-passed", a_qc)):
        for g in ("case", "control"):
            s = d[d.group == g]
            rows.append({"set": label, "group": g, "n": len(s),
                         **{c: int(s[c].astype(bool).sum()) for c in PROVENANCE}})
    counts = pd.DataFrame(rows)
    counts.to_csv(ROOT / "out" / "posthoc_report_provenance_designA.csv", index=False)

    hv = df[df.ecg_id.map(db["validated_by_human"]).astype(bool)]
    n_case, n_ctrl = int(hv.case.sum()), int((hv.case == 0).sum())
    model = None
    if n_case >= MIN_CASES_POSTHOC:
        model = gc.ols_group(hv, gc.PRIMARY)
    return counts, n_case, n_ctrl, model


def main():
    plan = ROOT / "paper" / "notes" / "analysis_plan.md"
    print("analysis_plan.md sha256:", hashlib.sha256(plan.read_bytes()).hexdigest())
    pd.set_option("display.width", 300)
    pd.set_option("display.max_columns", 99)

    df = load_design_a()
    print("\n== Sensitivity 1: complete matched sets ==")
    print(sens1(df).round(4).to_string())

    print("\n== Sensitivity 2: Design B ==")
    flow, out, dfb = sens2()
    print(flow.pivot_table(index="rule", columns="group", values=["any", "first"],
                           sort=False).to_string())
    print("post-QC n:", len(dfb), "cases:", int(dfb.case.sum()))
    print(out.round(4).to_string())

    print("\n== POST-HOC: report provenance ==")
    counts, n_case, n_ctrl, model = posthoc(df)
    print(counts.to_string())
    print(f"human-validated QC-passed subset: {n_case} cases, {n_ctrl} controls")
    if model:
        print("primary model on subset: diff %.3f (%.3f to %.3f), p %.4f" % model)
    else:
        print(f"fewer than {MIN_CASES_POSTHOC} cases: model not run")


if __name__ == "__main__":
    main()
